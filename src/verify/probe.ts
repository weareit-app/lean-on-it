// The inspection probe: a Lean file, written to a private run directory,
// that imports the declaring module and prints what Lean knows about one
// declaration. The declaration name and a per-run nonce reach it through
// environment variables, never through its source text; the only name in the
// source is the module, which has already passed checkLeanName.
import { z } from "zod";
import { checkLeanName } from "./trusted-workspace.ts";

export const PROBE_DECLARATION_ENV = "LEAN_ON_IT_DECLARATION";
export const PROBE_NONCE_ENV = "LEAN_ON_IT_NONCE";
const MARKER = "LEAN_ON_IT_EVIDENCE";

export function probeSource(module: string): string {
  checkLeanName("module", module);
  return `import Lean
import ${module}

/-! Generated by lean-on-it: inspects one declaration and prints a JSON
record of its kind, elaborated type, axioms and dependency closure. -/

open Lean Elab Command

/-- Constants reachable from a declaration through types and values. -/
private partial def leanOnItClosure (env : Environment) (root : Name) : NameSet := Id.run do
  let mut seen : NameSet := {}
  let mut todo := #[root]
  while h : todo.size > 0 do
    let n := todo.back
    todo := todo.pop
    if seen.contains n then continue
    seen := seen.insert n
    if let some ci := env.find? n then
      for m in ci.getUsedConstantsAsSet do
        unless seen.contains m do todo := todo.push m
  return seen

run_cmd do
  let some declStr ← (IO.getEnv "${PROBE_DECLARATION_ENV}" : IO _) | throwError "${PROBE_DECLARATION_ENV} is not set"
  let some nonce ← (IO.getEnv "${PROBE_NONCE_ENV}" : IO _) | throwError "${PROBE_NONCE_ENV} is not set"
  let n := declStr.toName
  let env ← getEnv
  let moduleOf (c : Name) : Option Name :=
    (env.getModuleIdxFor? c).bind fun i => env.header.moduleNames[i.toNat]?
  let record ← match env.find? n with
    | none => pure (Json.mkObj [("found", false)])
    | some ci => do
      let kind := match ci with
        | .thmInfo _ => "theorem" | .defnInfo _ => "definition"
        | .axiomInfo _ => "axiom" | .opaqueInfo _ => "opaque" | _ => "other"
      let pretty ← liftTermElabM do return toString (← Meta.ppExpr ci.type)
      let explicit ← liftTermElabM do
        withOptions (fun o => o.set \`pp.all true) do return toString (← Meta.ppExpr ci.type)
      let axioms : Json ← try
          pure (Json.mkObj [("names", toJson ((← collectAxioms n).map toString))])
        catch e => pure (Json.mkObj [("error", toJson (← e.toMessageData.toString))])
      let closure := leanOnItClosure env n
      let modules := closure.toList.filterMap moduleOf |>.foldl (·.insert ·) ({} : NameSet)
      pure <| Json.mkObj [
        ("found", true), ("kind", kind),
        ("module", toJson ((moduleOf n).map toString)),
        ("levelParams", toJson (ci.levelParams.map toString)),
        ("typePretty", pretty), ("typeExplicit", explicit),
        ("axioms", axioms),
        ("direct", toJson (ci.getUsedConstantsAsSet.toList.map toString)),
        ("closure", toJson (closure.toList.map toString)),
        ("closureModules", toJson (modules.toList.map toString))]
  logInfo m!"${MARKER}:{nonce}:{record.compress}"
`;
}

const probeRecordSchema = z.union([
  z.object({ found: z.literal(false) }),
  z.object({
    found: z.literal(true),
    kind: z.enum(["theorem", "definition", "axiom", "opaque", "other"]),
    module: z.string().nullable(),
    levelParams: z.array(z.string()),
    typePretty: z.string().min(1),
    typeExplicit: z.string().min(1),
    axioms: z.union([
      z.object({ names: z.array(z.string()) }),
      z.object({ error: z.string() }),
    ]),
    direct: z.array(z.string()),
    closure: z.array(z.string()),
    closureModules: z.array(z.string()),
  }),
]);

export type ProbeRecord = z.infer<typeof probeRecordSchema>;

/**
 * The probe's record from `lean --json` output, or null if no message carries
 * this run's nonce or the record is malformed.
 */
export function parseProbeOutput(
  stdout: string,
  nonce: string,
): ProbeRecord | null {
  const prefix = `${MARKER}:${nonce}:`;
  for (const line of stdout.split("\n")) {
    let message: unknown;
    try {
      message = JSON.parse(line);
    } catch {
      continue;
    }
    const data = (message as { data?: unknown }).data;
    if (typeof data !== "string" || !data.startsWith(prefix)) continue;
    try {
      const parsed = probeRecordSchema.safeParse(
        JSON.parse(data.slice(prefix.length)),
      );
      return parsed.success ? parsed.data : null;
    } catch {
      return null;
    }
  }
  return null;
}

export interface LeanDiagnostics {
  errors: number;
  warnings: number;
  sorryWarnings: number;
}

/** Counts of `lean --json` messages by severity, and `sorry` warnings. */
export function countDiagnostics(stdout: string): LeanDiagnostics {
  const counts = { errors: 0, warnings: 0, sorryWarnings: 0 };
  for (const line of stdout.split("\n")) {
    let message: { severity?: unknown; kind?: unknown; data?: unknown };
    try {
      message = JSON.parse(line);
    } catch {
      continue;
    }
    if (message.severity === "error") counts.errors++;
    if (message.severity === "warning") {
      counts.warnings++;
      const data = typeof message.data === "string" ? message.data : "";
      if (
        message.kind === "hasSorry" ||
        /declaration uses [`']sorry[`']/.test(data)
      )
        counts.sorryWarnings++;
    }
  }
  return counts;
}
